static uint32_t find_child_index(void* node, uint32_t key) {
    NodeHeader* header = get_node_header(node);
    uint32_t* keys = get_node_keys(node);
    
    uint32_t left = 0;
    uint32_t right = header->num_keys;
    
    while (left < right) {
        uint32_t mid = (left + right) / 2;
        if (keys[mid] >= key) {
            right = mid;
        } else {
            left = mid + 1;
        }
    }
    
    return left;
}

