    Value v = {0};
    v.type = COL_TYPE_TEXT;
    if (str) {
        size_t len = strlen(str);
        v.value.text.data = malloc(len + 1);
        if (v.value.text.data) {
            strcpy(v.value.text.data, str);
            v.value.text.length = len;
        }
    }
    v.is_null = (str == NULL);
    return v;
