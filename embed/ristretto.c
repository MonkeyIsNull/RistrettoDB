bool create_data_directory_in(const char *base_dir) {
    if (!base_dir) base_dir = "data";
    struct stat st = {0};
    if (stat(base_dir, &st) == -1) {
        if (mkdir(base_dir, 0755) == 0) return true;
        // Tolerate a concurrent creator.
        return errno == EEXIST;
    }
    return true;
}

